def assign_portraits(region, suspects):
    """suspects: [{job, gender}] → 같은 순서의 초상화 경로 (없으면 None).
    한 에피소드 안에서는 같은 그림을 두 번 쓰지 않는다."""
    reg = REGION_KEY.get(region)
    if not reg:
        return [None] * len(suspects)
    female = POOL_FEMALE[reg]
    used, borrowed, out = set(), set(), []
    for s in suspects:
        want_f = s['gender'] == '여'
        ok = lambda i: i not in used and ((i in female) == want_f)
        pick = next((i for i in JOB_PREFS.get(s['job'], []) if ok(i)), None)
        if pick is None:
            pick = next((i for i in GENDER_FALLBACK['여' if want_f else '남'] if ok(i)), None)
        if pick is None:
            # 같은 대륙에 맞는 성별 그림이 다 쓰였으면 다른 대륙 풀에서 같은 직업·성별 → 같은 성별 순으로 빌려 온다
            other = next(((r, i) for r in POOL_FEMALE if r != reg
                          for i in JOB_PREFS.get(s['job'], []) + GENDER_FALLBACK['여' if want_f else '남']
                          if (i in POOL_FEMALE[r]) == want_f and (r, i) not in borrowed), None)
            if other is None:
                out.append(None)
                continue
            borrowed.add(other)
            out.append(f'{ART_DIR}/suspect/{other[0]}_{other[1]:02d}.jpg')
            continue
        used.add(pick)
        out.append(f'{ART_DIR}/suspect/{reg}_{pick:02d}.jpg')
    return out
