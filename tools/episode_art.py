def bg_for(no, country, text):
    choices = COUNTRY_BG.get(country)
    if not choices:
        return None
    for words, key in BG_KEYWORDS:
        if key in choices and any(w in text for w in words):
            return f'{ART_DIR}/bg/{key}.jpg'
    return f'{ART_DIR}/bg/{choices[no % len(choices)]}.jpg'


