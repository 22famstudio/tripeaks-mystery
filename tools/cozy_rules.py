_SPLIT = re.compile(r'(?<=[.?!…])(\s+)')


def rewrite_sentences(text):
    """문장 단위 코지 치환 (공백 · 줄바꿈 그대로)"""
    if not text:
        return text
    parts = _SPLIT.split(text)
    return ''.join(SENTENCES.get(p, p) for p in parts)


def rewrite_words(text):
    for pat, repl in WORDS:
        text = re.sub(pat, repl, text)
    return text


def cozy(text):
    return rewrite_words(rewrite_sentences(text))


def banned_in(text):
    """남은 금지어 목록 ('커피를' · '피로가' 같은 일상어는 제외)"""
    found = []
    for w in BANNED:
        for m in re.finditer(re.escape(w), text or ''):
            if w.startswith('피') and m.start() > 0 and text[m.start() - 1] in '커소혈갈포알창':
                continue
            found.append(w)
    return found
