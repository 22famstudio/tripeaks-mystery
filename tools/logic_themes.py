SPOT_KEYS = sorted(THEMES, key=len, reverse=True)


def theme_for(place):
    """'부산의 음산한 고급 저택' → '고급 저택' (공간 이름이 장소 끝에 붙어 있다)"""
    return next((k for k in SPOT_KEYS if place.endswith(k)), None)


def pick(no, place, n_places=5, n_items=5):
    """에피소드 번호 고정 시드로 (장소 6 · 물건 6) 이름 — 마지막이 사건 현장 / 범행 도구"""
    key = theme_for(place)
    if not key:
        return None
    t = THEMES[key]
    rng = random.Random(no * 104729 + 17)
    places = rng.sample(t['places'], n_places) + [f"{rng.choice(t['crime'])}(사건현장)"]
    items = rng.sample(t['items'], n_items) + [f"{rng.choice(t['weapon'])}(범행도구)"]
    return places, items


def rename(logic, old_places, old_items, new_places, new_items):
    """단서 1~21 문장 속 장소 · 물건 이름을 1:1로 바꾼 새 항목 (원본은 그대로). 긴 이름부터 자리표시로 바꿔 겹침 방지"""
    pairs = list(zip(old_places, new_places)) + list(zip(old_items, new_items))
    out = dict(logic)
    for key, text in logic.items():
        if not key.startswith('단서'):
            continue
        marks = {}
        for i, (old, new) in enumerate(sorted(pairs, key=lambda p: len(p[0]), reverse=True)):
            tag = f'\u0001{i}\u0002'
            if old in text:
                text = text.replace(old, tag)
                marks[tag] = new
        for tag, new in marks.items():
            text = text.replace(tag, new)
        out[key] = text
    return out
